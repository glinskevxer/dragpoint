"""Writing a generated document, or checking that it is still right.

Every generator here does the same two things and it matters that they do
them the same way. Run plain, it writes the file. Run with ``--check``, it
writes nothing and exits one if what is on disk is not what it would have
written.

The second form is what CI uses, and it is the only thing that makes a
generated document worth having. A document that is generated and never
checked drifts from the code it came from, and then it is worse than no
document, because it is a wrong document with the authority of an
automatically produced one.
"""

from __future__ import annotations

import sys
from collections.abc import Sequence
from pathlib import Path

__all__ = ["HEADER", "generated", "run"]

HEADER = "<!-- Generated by {tool}. Do not edit; edit the code and run it again. -->"
"""The first line of every generated document, so nobody edits one by hand."""


def generated(tool: str, title: str, body: Sequence[str]) -> str:
    """Assemble a document with its warning line and its title."""
    lines = [HEADER.format(tool=tool), "", f"# {title}", ""]
    lines.extend(body)
    return "\n".join(lines).rstrip() + "\n"


def run(path: Path, text: str, arguments: Sequence[str]) -> int:
    """Write ``text`` to ``path``, or check what is there against it.

    Nothing is written in check mode, not even when the file is missing. A
    generator that fixed the problem it was asked to report would make the
    CI job that runs it pass on the second attempt for the wrong reason.
    """
    checking = "--check" in arguments
    if not checking:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        return 0
    if not path.is_file():
        print(f"{path} is missing, run the generator", file=sys.stderr)
        return 1
    if path.read_text(encoding="utf-8") != text:
        print(f"{path} is out of date, run the generator", file=sys.stderr)
        return 1
    print(f"{path.name} is up to date")
    return 0
