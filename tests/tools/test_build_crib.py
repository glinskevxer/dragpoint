"""The crib page."""

from __future__ import annotations

import pytest

from dragpoint.tool.cutter import CATALOGUE, catalogue_cutter
from dragpoint.tool.material import MATERIALS
from dragpoint.tools import build_crib
from dragpoint.tools.support import DOCS


def page() -> str:
    return (DOCS / "crib.md").read_text(encoding="utf-8")


def test_the_page_is_up_to_date(capsys: pytest.CaptureFixture[str]) -> None:
    assert build_crib.main(["--check"]) == 0
    assert "up to date" in capsys.readouterr().out


def test_every_cutter_is_on_the_page() -> None:
    text = page()
    for name in CATALOGUE:
        assert f"`{name}`" in text


def test_every_stock_is_on_the_page() -> None:
    text = page()
    for name in MATERIALS:
        assert f"`{name}`" in text


def test_the_groove_widths_are_worked_out_and_not_typed() -> None:
    cutter = catalogue_cutter("V30-015")
    assert build_crib._groove_at(cutter, 0.2) == f"{cutter.width_at_depth(0.2):.3f}"


def test_a_depth_the_cutter_cannot_reach_is_a_dash() -> None:
    cutter = catalogue_cutter("V90-030")
    assert build_crib._groove_at(cutter, 5.0) == "-"


def test_a_parallel_cutter_says_parallel_rather_than_zero() -> None:
    assert "| parallel |" in page()


def test_the_depth_window_of_every_sheet_is_on_the_page() -> None:
    text = page()
    for sheet in MATERIALS.values():
        low, high = sheet.depth_window()
        assert f"{low:.2f} to {high:.2f}" in text


def test_solid_stock_says_solid_rather_than_a_cap_thickness() -> None:
    assert "| solid |" in page()


def test_the_page_explains_why_a_laminate_has_a_floor() -> None:
    assert "cap never breaks through" in page()


def test_the_page_says_it_is_generated() -> None:
    assert page().splitlines()[0].startswith("<!-- Generated by dragpoint.tools.build_crib")
