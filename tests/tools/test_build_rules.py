"""The rule reference."""

from __future__ import annotations

import pytest

from dragpoint.rules.check import REGISTRY
from dragpoint.tools import build_rules
from dragpoint.tools.support import DOCS


def page() -> str:
    return (DOCS / "rules.md").read_text(encoding="utf-8")


def test_the_page_is_up_to_date(capsys: pytest.CaptureFixture[str]) -> None:
    assert build_rules.main(["--check"]) == 0
    assert "up to date" in capsys.readouterr().out


def test_every_rule_that_runs_is_on_the_page() -> None:
    text = page()
    for name in REGISTRY:
        assert f"`{name}`" in text


def test_nothing_is_on_the_page_that_does_not_run() -> None:
    listed = {
        line.split("|")[1].strip().strip("`")
        for line in page().splitlines()
        if line.startswith("| `") and "severity" not in line
    }
    assert listed <= set(REGISTRY) | {name for name in listed if not name}


def test_every_severity_is_written_as_a_word() -> None:
    text = page()
    assert "| error |" in text
    assert "| warning |" in text
    assert "| note |" in text


def test_the_page_explains_what_a_severity_means() -> None:
    assert "## Severity" in page()


def test_the_numbers_the_rules_turn_on_are_listed() -> None:
    text = page()
    assert "## The numbers" in text
    assert "fold ratio" in text
    assert "weight ratio" in text


def test_the_page_says_it_is_generated() -> None:
    assert page().splitlines()[0].startswith("<!-- Generated by dragpoint.tools.build_rules")
