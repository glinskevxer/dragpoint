"""The command reference."""

from __future__ import annotations

import click
import pytest

from dragpoint.cli.main import main as root
from dragpoint.tools import build_commands
from dragpoint.tools.support import DOCS


def page() -> str:
    return (DOCS / "commands.md").read_text(encoding="utf-8")


def test_the_page_is_up_to_date(capsys: pytest.CaptureFixture[str]) -> None:
    assert build_commands.main(["--check"]) == 0
    assert "up to date" in capsys.readouterr().out


def test_every_command_that_exists_is_on_the_page() -> None:
    text = page()
    assert isinstance(root, click.Group)
    for name, entry in root.commands.items():
        if not isinstance(entry, click.Group):
            assert f"dragpoint {name}" in text
            continue
        for command_name in entry.commands:
            assert f"dragpoint {name} {command_name}" in text


def test_every_group_gets_a_heading() -> None:
    text = page()
    for name in root.commands:
        assert f"## `dragpoint {name}`" in text


def test_a_command_hung_off_the_root_gets_its_own_section() -> None:
    text = page()
    assert "## `dragpoint pack`" in text
    assert "### `dragpoint pack SCHEDULE`" in text


def test_the_help_option_is_not_worth_a_row() -> None:
    assert "| `--help`" not in page()


def test_an_option_carries_its_help_and_its_default() -> None:
    text = page()
    assert "| `--cap-height` | Lettering height. | `3mm` |" in text


def test_a_flag_that_is_off_shows_no_default() -> None:
    assert "| `--mirror` | Cut it back to front. |  |" in page()


def test_arguments_are_in_the_usage_line() -> None:
    assert "dragpoint plate check [LINES...]" in page()
    assert "dragpoint job check SCHEDULE" in page()


def test_the_summary_of_a_command_is_its_first_help_line() -> None:
    group = root.commands["crib"]
    assert isinstance(group, click.Group)
    assert build_commands._summary(group.commands["posts"]) == "List the post processors."


def test_the_exit_codes_are_explained() -> None:
    text = page()
    assert "exits zero" in text
    assert "two when the" in text


def test_the_page_says_it_is_generated() -> None:
    assert page().splitlines()[0].startswith("<!-- Generated by dragpoint.tools.build_commands")
